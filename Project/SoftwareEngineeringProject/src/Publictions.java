
public class Publictions {
	
	private int level;
	private int freq;
	private double price;
	public int getLevel() {
		return level;
	}
	public void setLevel(int level) {
		this.level = level;
	}
	public int getFreq() {
		return freq;
	}
	public void setFreq(int freq) {
		this.freq = freq;
	}
	public double getPrice() {
		return price;
	}
	public void setPrice(double price) {
		this.price = price;
	}
	public Publictions(int level, int freq, double price) {
		this.level = level;
		this.freq = freq;
		this.price = price;
	}
	
	
	

}
